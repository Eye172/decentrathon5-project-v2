"""
AI text detection — hybrid approach:
1. Claude API (primary, accurate) — detects AI patterns semantically
2. Statistical heuristics (fallback) — works without API key
"""
import re
import math
import os
import json
import anthropic
from dotenv import load_dotenv

load_dotenv()

DETECTION_SYSTEM_PROMPT = """You are an expert in detecting AI-generated text. 
You analyze essays and interview answers to determine if they were written by a human or generated by AI tools like ChatGPT, Claude, or similar.

Signs of AI-generated text:
- Overly polished, generic phrasing with no personal voice
- Perfect paragraph structure with no natural flow or tangents
- Heavy use of formal connectors ("таким образом", "следует отметить", "в заключение", "furthermore", "moreover")
- Lack of specific personal details, concrete memories, named people
- Uniform sentence complexity and length
- Abstract statements without grounding in real experience
- Clichés about leadership, motivation, impact without authentic backing
- Reads like a template or a "model answer"

Signs of human-written text:
- Specific personal details (names, places, exact moments)
- Inconsistent style — some sentences formal, some casual
- Emotional honesty including self-doubt, mistakes, confusion
- Non-linear thinking, tangents, unpolished moments
- Unique observations that couldn't be generic advice
- Concrete sensory details

Respond ONLY with valid JSON, no markdown."""


def detect_ai_text(text: str) -> dict:
    """
    Primary: Claude-based detection.
    Fallback: statistical heuristics if no API key.
    """
    api_key = os.getenv("ANTHROPIC_API_KEY")
    if api_key and api_key != "your_claude_api_key_here":
        try:
            return _detect_with_claude(text, api_key)
        except Exception:
            pass
    return _detect_statistical(text)


def _detect_with_claude(text: str, api_key: str) -> dict:
    client = anthropic.Anthropic(api_key=api_key)

    prompt = f"""Analyze this text and determine if it was written by a human or generated by AI.

TEXT TO ANALYZE:
---
{text[:3000]}
---

Return EXACTLY this JSON (no markdown):
{{
  "score": <float 0.0 to 1.0, where 0=definitely human, 1=definitely AI>,
  "risk_level": "<low|medium|high>",
  "reasoning": "<2-3 sentences explaining the key signals you found>",
  "human_signals": ["<signal 1>", "<signal 2>"],
  "ai_signals": ["<signal 1>", "<signal 2>"],
  "burstiness": <float 0.0-1.0, estimate of sentence variety>,
  "vocabulary_richness": <float 0.0-1.0, estimate of lexical diversity>,
  "avg_sentence_length": <float, estimated average words per sentence>
}}

Risk level guide: low = score < 0.35, medium = 0.35-0.60, high > 0.60"""

    message = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=600,
        system=DETECTION_SYSTEM_PROMPT,
        messages=[{"role": "user", "content": prompt}],
    )

    raw = message.content[0].text.strip()
    if raw.startswith("```"):
        raw = raw.split("```")[1]
        if raw.startswith("json"):
            raw = raw[4:]
    raw = raw.strip()

    result = json.loads(raw)

    # Normalize score to 0-1
    result["score"] = round(max(0.0, min(1.0, float(result["score"]))), 3)

    # Ensure risk_level matches score
    score = result["score"]
    if score < 0.35:
        result["risk_level"] = "low"
    elif score < 0.60:
        result["risk_level"] = "medium"
    else:
        result["risk_level"] = "high"

    result["method"] = "claude"
    return result


def _detect_statistical(text: str) -> dict:
    """Fallback: pure statistical heuristics."""
    words = re.findall(r"\b\w+\b", text)
    sentences = _split_sentences(text)
    sentence_lengths = [len(s.split()) for s in sentences]

    burstiness = _burstiness(sentence_lengths)
    vocab_richness = _vocabulary_richness(words)
    avg_len = _avg_sentence_length(sentence_lengths)

    # AI score
    burstiness_ai = max(0.0, 1.0 - burstiness * 2.5)
    vocab_ai = max(0.0, 1.0 - vocab_richness * 1.8)
    len_ai = min(1.0, max(0.0, (avg_len - 15) / 20))

    ai_score = round(min(1.0, max(0.0,
        0.40 * burstiness_ai + 0.40 * vocab_ai + 0.20 * len_ai
    )), 3)

    if ai_score < 0.35:
        risk_level = "low"
    elif ai_score < 0.60:
        risk_level = "medium"
    else:
        risk_level = "high"

    return {
        "score": ai_score,
        "burstiness": round(burstiness, 3),
        "vocabulary_richness": round(vocab_richness, 3),
        "avg_sentence_length": round(avg_len, 1),
        "risk_level": risk_level,
        "reasoning": "Статистический анализ (API ключ не задан)",
        "human_signals": [],
        "ai_signals": [],
        "method": "statistical",
    }


def _split_sentences(text: str) -> list[str]:
    sentences = re.split(r"(?<=[.!?])\s+", text.strip())
    return [s for s in sentences if len(s.split()) >= 2]


def _burstiness(lengths: list[int]) -> float:
    if len(lengths) < 3:
        return 0.5
    mean = sum(lengths) / len(lengths)
    variance = sum((l - mean) ** 2 for l in lengths) / len(lengths)
    std = math.sqrt(variance)
    cv = std / mean if mean > 0 else 0
    return min(cv / 1.0, 1.0)


def _vocabulary_richness(words: list[str]) -> float:
    if not words:
        return 0.0
    return len(set(w.lower() for w in words)) / len(words)


def _avg_sentence_length(lengths: list[int]) -> float:
    if not lengths:
        return 0.0
    return sum(lengths) / len(lengths)
